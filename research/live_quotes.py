"""
research/live_quotes.py

Near-live last traded prices for the stocks the paper books hold (or would hold), for the web app's
Paper trading page. Research only: it READS prices (data/upstox_client.py, the read-only client) and
writes one JSON file. It places no orders and the books never use these prices; they run on daily
bars. This is a display.

Why a separate writer and not the API calling Upstox: the web app's API is deliberately unable to import
any data, engine or research code (tests enforce it). Same pattern as everything else in the app:
a terminal command writes a file, the read-only API serves it, the page shows it.

Honest limits:
  * It polls (every 10 s while the market is open), so it is near-live, not tick-by-tick.
  * Market hours are Monday-Friday 09:15-15:30 IST. Exchange holidays are NOT known here, so on a
    holiday it says "open" but the prices simply do not move.
  * The Upstox access token has to be regenerated by hand in Upstox Developer Apps (it expires), so
    "live" needs a person once a day. When it has expired this writes a clear reason instead of prices.

    python research/live_quotes.py              # one fetch, then exit
    python research/live_quotes.py --loop       # keep refreshing (Ctrl+C to stop)
    python research/live_quotes.py --symbols RELIANCE TCS
"""

import argparse
import json
import os
import sys
import time
from datetime import datetime, timedelta, timezone

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(PROJECT_ROOT, "data"))
sys.path.insert(0, PROJECT_ROOT)

import upstox_client

IST = timezone(timedelta(hours=5, minutes=30))
BOOKS_PATH = os.path.join(PROJECT_ROOT, "reports", "output", "forward_books_latest.json")
LATEST_PATH = os.path.join(PROJECT_ROOT, "reports", "output", "live_quotes_latest.json")
POLL_OPEN_SECONDS = 10
POLL_CLOSED_SECONDS = 300            # outside market hours the price is the last close; no need to hammer
POLL_ERROR_SECONDS = 60
MARKET_NOTE = "Market hours are Mon-Fri 09:15-15:30 IST. Exchange holidays are not known, so a holiday shows as open with unchanged prices."


def market_status(now: datetime) -> str:
    """'open' (Mon-Fri 09:15-15:30 IST), 'pre-open' (09:00-09:15) or 'closed'. `now` must be timezone-aware."""
    t = now.astimezone(IST)
    if t.weekday() >= 5:
        return "closed"
    minutes = t.hour * 60 + t.minute
    if 9 * 60 + 15 <= minutes < 15 * 60 + 30:
        return "open"
    if 9 * 60 <= minutes < 9 * 60 + 15:
        return "pre-open"
    return "closed"


def holdings_by_symbol(path: str = BOOKS_PATH) -> dict:
    """{symbol: [ids of the books that hold it or would hold it (target weights count)]}, symbols sorted."""
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        books = json.load(f).get("books", [])
    held = {}
    for b in books:
        for h in b.get("holdings", []):
            held.setdefault(h["symbol"], []).append(b["id"])
    return dict(sorted(held.items()))


def symbols_from_books(path: str = BOOKS_PATH) -> list:
    """Every stock any paper book holds or would hold, sorted, no duplicates."""
    return list(holdings_by_symbol(path))


def _reason_for(error: Exception) -> str:
    """A plain-language reason for the page. The client's messages never contain the token."""
    text = str(error)
    if "UPSTOX_ACCESS_TOKEN is not set" in text:
        return "No Upstox access token is set. Generate one in Upstox Developer Apps and set UPSTOX_ACCESS_TOKEN."
    if "HTTP 401" in text:
        return "The Upstox access token has expired or is invalid. Generate a new one in Upstox Developer Apps and set UPSTOX_ACCESS_TOKEN."
    return f"Could not fetch quotes: {text[:160]}"


def build_payload(quotes: dict | None, requested: list, now: datetime, error: str | None = None,
                  held_by: dict | None = None) -> dict:
    """The file's contents. Change % is worked out here (the page only displays numbers, it never computes them)."""
    rows = []
    for symbol in requested if error is None else []:
        q = (quotes or {}).get(symbol) or {}
        last, prev = q.get("last_price"), q.get("prev_close")
        change = round((last - prev) / prev * 100, 2) if last is not None and prev else None
        rows.append({"symbol": symbol, "last_price": last, "prev_close": prev, "change_pct": change,
                     "volume": q.get("volume"), "held_by": (held_by or {}).get(symbol, [])})
    return {"generated_at": now.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "market_status": market_status(now), "market_note": MARKET_NOTE,
            "available": error is None, "reason": error, "n_requested": len(requested), "quotes": rows}


def write_latest(payload: dict, path: str = LATEST_PATH) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=1, allow_nan=False)       # NaN is not valid JSON: fail loudly, never write it
    os.replace(tmp, path)                                      # atomic: a reader never sees half a file


def run_once(symbols: list, instrument_map: dict | None = None, now: datetime | None = None, path: str = LATEST_PATH,
             held_by: dict | None = None) -> dict:
    """Fetch once and write the file. A failure is written as a reason, never raised, so the page can explain it."""
    now = now or datetime.now(timezone.utc)
    try:
        quotes = upstox_client.get_ltp(symbols, instrument_map)
        payload = build_payload(quotes, symbols, now, held_by=held_by)
    except RuntimeError as e:
        payload = build_payload(None, symbols, now, error=_reason_for(e))
    write_latest(payload, path)
    return payload


def next_pause(payload: dict) -> int:
    if not payload["available"]:
        return POLL_ERROR_SECONDS
    return POLL_OPEN_SECONDS if payload["market_status"] == "open" else POLL_CLOSED_SECONDS


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Write near-live prices for the paper books' stocks (read-only).")
    ap.add_argument("--loop", action="store_true", help="keep refreshing until stopped")
    ap.add_argument("--symbols", nargs="+", help="override the stocks (default: every stock the paper books hold)")
    args = ap.parse_args(argv)

    instruments = upstox_client.load_instrument_map()
    while True:
        held_by = holdings_by_symbol()
        symbols = args.symbols or list(held_by)
        if not symbols:
            print("[live] no stocks to quote: run python research/forward_books.py first, or pass --symbols")
            return 1
        payload = run_once(symbols, instruments, held_by=held_by)
        stamp = datetime.now(IST).strftime("%H:%M:%S")
        if payload["available"]:
            got = sum(1 for q in payload["quotes"] if q["last_price"] is not None)
            print(f"[live] {stamp} IST market {payload['market_status']}: {got} of {len(symbols)} prices written")
        else:
            print(f"[live] {stamp} IST {payload['reason']}")
        if not args.loop:
            return 0 if payload["available"] else 1
        time.sleep(next_pause(payload))


if __name__ == "__main__":
    sys.exit(main())
