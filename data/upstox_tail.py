"""
data/upstox_tail.py

Fills the NEWEST trading sessions that yfinance has not priced yet, from the read-only Upstox market-data client.
Research only (CLAUDE.md rule 5): it reaches only the historical-candle endpoint through data/upstox_client.py's gate, so
no order, position, holdings or funds data is ever requested, and the token stays in the Windows environment.

Why it exists: Yahoo lists the newest session with a volume but no prices for hours after the close (data/known_issues.md,
2026-10-20), which can hold the forward paper tests back a day. The daily forward run registers this as the loader's tail
source (data.loader.set_tail_source). It only ever supplies sessions AFTER yfinance's last priced day, and only when such a
session should exist, so on a normal evening (Yahoo has priced the day) it makes no request at all. What it supplies goes
through the loader's usual cleaning and is replaced by Yahoo's own value as soon as Yahoo prices that day.

Prices differ in basis from yfinance's adjusted series (Upstox is split/bonus adjusted, not dividend adjusted), which only
matters if a dividend goes ex inside the few days it fills; the validator's discontinuity gate still sees the joined series.
"""

import csv
import os
from datetime import datetime, time as dtime, timedelta, timezone

import pandas as pd

import upstox_client

MARKET_CLOSE_IST = dtime(16, 0)               # the NSE session ends 15:30; wait until 16:00 before expecting a complete day
LOOKBACK_DAYS = 4                              # a one-day window can come back empty from the API, so ask a little wider and trim
LOG_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cache", "upstox_tail_log.csv")     # git-ignored with the cache


def expected_last_session(now_utc: datetime) -> pd.Timestamp:
    """
    The most recent weekday whose session should be complete at `now_utc` (the NSE trades Monday to Friday, 09:15 to 15:30
    India time). Exchange holidays are unknown here: on one, the API simply returns nothing for that day.
    """
    ist = now_utc.astimezone(timezone(timedelta(hours=5, minutes=30)))
    day = ist.date() if ist.time() >= MARKET_CLOSE_IST else ist.date() - timedelta(days=1)
    while day.weekday() >= 5:                  # Saturday or Sunday: step back to Friday
        day -= timedelta(days=1)
    return pd.Timestamp(day)


class UpstoxTail:
    """A callable `tail(symbol, start, end) -> DataFrame` for data.loader.set_tail_source."""

    def __init__(self, now=None, fetch_range=None, fetch_today=None, log_path: str | None = LOG_PATH):
        self._now = now or (lambda: datetime.now(timezone.utc))
        self._fetch_range = fetch_range or upstox_client.fetch_symbol_daily
        self._fetch_today = fetch_today or upstox_client.fetch_today_daily
        self._log_path = log_path
        self._map = None
        self._disabled = False                     # set after a rejected token, so one bad token costs one request, not hundreds

    def _instruments(self) -> dict:
        if self._map is None:
            self._map = upstox_client.load_instrument_map()
        return self._map

    def __call__(self, symbol: str, start: pd.Timestamp, end: pd.Timestamp) -> pd.DataFrame:
        if self._disabled:
            return pd.DataFrame()
        try:
            return self._fetch(symbol, start, end)
        except RuntimeError as e:
            if "HTTP 401" in str(e) or "HTTP 403" in str(e):          # an expired or rejected token (it is regenerated by hand each day)
                self._disabled = True
                print("[upstox-tail] the token was rejected; the newest sessions will come from Yahoo alone this run. Regenerate the token to use Upstox.")
                return pd.DataFrame()
            raise

    def _fetch(self, symbol: str, start: pd.Timestamp, end: pd.Timestamp) -> pd.DataFrame:
        wanted_through = min(pd.Timestamp(end).normalize(), expected_last_session(self._now()))
        start = pd.Timestamp(start).normalize()
        if wanted_through < start:                                   # no new session should exist yet: no request at all
            return pd.DataFrame()
        today = pd.Timestamp(self._now().astimezone(timezone(timedelta(hours=5, minutes=30))).date())
        pieces = []
        if start < wanted_through or wanted_through != today:        # sessions before today come from the completed-days endpoint
            pieces.append(self._fetch_range(symbol, str((start - pd.Timedelta(days=LOOKBACK_DAYS)).date()), str(wanted_through.date()), self._instruments()))
        if wanted_through == today:                                  # today's candle comes from the intraday endpoint
            pieces.append(self._fetch_today(symbol, self._instruments()))
        pieces = [p for p in pieces if p is not None and not p.empty]
        if not pieces:
            return pd.DataFrame()
        frame = pd.concat(pieces)
        frame = frame[~frame.index.duplicated(keep="last")].sort_index()
        frame = frame[(frame.index >= start) & (frame.index <= wanted_through)]
        self._log(symbol, frame)
        return frame

    def _log(self, symbol: str, frame: pd.DataFrame) -> None:
        """One line per day supplied, so it is always possible to see which rows came from this source."""
        if frame.empty or not self._log_path:
            return
        os.makedirs(os.path.dirname(self._log_path), exist_ok=True)
        new = not os.path.exists(self._log_path)
        with open(self._log_path, "a", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            if new:
                w.writerow(["logged_utc", "symbol", "bar_date", "close", "source"])
            for day, row in frame.iterrows():
                w.writerow([self._now().strftime("%Y-%m-%dT%H:%M:%SZ"), symbol, day.strftime("%Y-%m-%d"), float(row["close"]), "upstox"])


def available() -> bool:
    """True when an Upstox access token is configured. Without one the daily run simply uses yfinance alone."""
    return bool(upstox_client.get_credential("UPSTOX_ACCESS_TOKEN"))
